def cargar(nombre):
    """Devuelve un diccionario con los parámetros generales y los datos por cliente."""
    familia = "PMD" if nombre.startswith("PMD") else "PC"
    datos = dict(PARAMETROS[familia])
    datos["nombre"] = nombre
    filas = CLIENTES[nombre]
    datos["M"] = [f[0] for f in filas]
    for i, clave in enumerate(["t_dep", "t_disp", "t_disp_dep", "t_unl", "t1", "t2", "s", "Q"], start=1):
        datos[clave] = {f[0]: f[i] for f in filas}
    return datos
